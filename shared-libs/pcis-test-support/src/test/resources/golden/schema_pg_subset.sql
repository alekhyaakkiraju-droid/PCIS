-- Schema-compatible subset for CI seed validation (PostgreSQL)
CREATE TABLE IF NOT EXISTS CLAIM_RESERVE_T (
  CLAIM_ID VARCHAR(16), RESERVE_ID VARCHAR(16), RESERVE_STATUS CHAR(2),
  RESERVE_AMT NUMERIC(11,2), AUTHORITY_LIMIT NUMERIC(11,2)
);
CREATE TABLE IF NOT EXISTS CLAIM_PAYMENT_T (
  PAYMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  CLAIM_ID VARCHAR(16), PAYMENT_AMT NUMERIC(11,2), CREATED_AT TIMESTAMP
);
CREATE TABLE IF NOT EXISTS POLICY_T (
  POLICY_ID VARCHAR(16) PRIMARY KEY, BILLING_FREQ CHAR(1), ANNUAL_PREMIUM NUMERIC(11,2),
  STATUS CHAR(1), PREMIUM_DUE_DATE DATE, GRACE_DAYS INT, EXPIRY_DATE DATE
);
CREATE TABLE IF NOT EXISTS BILLING_INSTALLMENT_T (
  INSTALLMENT_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  POLICY_ID VARCHAR(16), INSTALLMENT_NO INT, AMOUNT NUMERIC(11,2)
);
CREATE TABLE IF NOT EXISTS AUDIT_LOG_T (
  LOG_ID BIGINT, PROGRAM_NAME VARCHAR(10), ACTION_CODE VARCHAR(3),
  TABLE_NAME VARCHAR(40), RECORD_KEY VARCHAR(40), USER_ID VARCHAR(10), LOG_TIMESTAMP VARCHAR(40)
);
CREATE TABLE IF NOT EXISTS AUDIT_LOG_ARCHIVE_T (
  LOG_ID BIGINT, PROGRAM_NAME VARCHAR(10), ACTION_CODE VARCHAR(3),
  TABLE_NAME VARCHAR(40), RECORD_KEY VARCHAR(40), USER_ID VARCHAR(10),
  LOG_TIMESTAMP VARCHAR(40), ARCHIVE_DATE DATE
);
CREATE TABLE IF NOT EXISTS COMMISSION_T (
  POLICY_ID VARCHAR(16), AGENT_ID VARCHAR(10), PREMIUM_AMT NUMERIC(11,2),
  COMM_CALC_FLAG CHAR(1), COMMISSION_AMT NUMERIC(9,2)
);
CREATE TABLE IF NOT EXISTS DEDUCTIBLE_T (
  POLICY_ID VARCHAR(16), DEDUCTIBLE_AMT NUMERIC(11,2)
);
CREATE TABLE IF NOT EXISTS RPT_RUN_LOG_T (
  RUN_ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
  PROGRAM_NAME VARCHAR(10), STATUS VARCHAR(20), ROWS_PROCESSED INT,
  RUN_STARTED TIMESTAMP, RUN_ENDED TIMESTAMP
);
