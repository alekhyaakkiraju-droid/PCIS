-- Minimal billing tables for PRM005B batch integration tests (WO-208)
CREATE TABLE IF NOT EXISTS BILLING_SCHEDULE_T (
    BILL_SCHED_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    POL_NBR VARCHAR(12) NOT NULL,
    BILL_PLAN_ID BIGINT NOT NULL DEFAULT 1,
    INSTALLMENT_NBR INTEGER NOT NULL,
    DUE_DATE DATE NOT NULL,
    AMT_DUE NUMERIC(11,2) NOT NULL,
    AMT_PAID NUMERIC(11,2),
    SCHED_STATUS CHAR(1) NOT NULL,
    CRT_USER VARCHAR(10),
    CRT_TIMESTAMP TIMESTAMP,
    UPD_USER VARCHAR(10),
    UPD_TIMESTAMP TIMESTAMP
);

CREATE TABLE IF NOT EXISTS RPT_RUN_LOG_T (
    RUN_LOG_ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    PGM_NAME VARCHAR(10) NOT NULL,
    RUN_DATE DATE NOT NULL,
    REC_SELECTED INTEGER NOT NULL DEFAULT 0,
    REC_UPDATED INTEGER NOT NULL DEFAULT 0,
    REC_ERRORS INTEGER NOT NULL DEFAULT 0,
    REC_DELINQUENT INTEGER,
    START_TIMESTAMP TIMESTAMP NOT NULL,
    END_TIMESTAMP TIMESTAMP NOT NULL,
    CRT_USER VARCHAR(10),
    CRT_TIMESTAMP TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS outbox_events (
    ID BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    AGGREGATE_TYPE VARCHAR(100) NOT NULL,
    AGGREGATE_ID VARCHAR(100) NOT NULL,
    EVENT_TYPE VARCHAR(100) NOT NULL,
    PAYLOAD JSONB NOT NULL,
    IDEMPOTENCY_KEY UUID NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    ATTEMPT_COUNT INTEGER NOT NULL DEFAULT 0,
    NEXT_ATTEMPT_AT TIMESTAMP,
    CRT_USER VARCHAR(10),
    CRT_TIMESTAMP TIMESTAMP NOT NULL
);

DELETE FROM outbox_events;
DELETE FROM BILLING_SCHEDULE_T;
DELETE FROM RPT_RUN_LOG_T WHERE PGM_NAME = 'PRM005B';
